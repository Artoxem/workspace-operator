"""Round-trip check: .pptx → Google Slides → replace text → read back → trash.

Verifies the two v1.2 paths that the regular live smoke cannot cover without a
deck that already contains text:

1. ``drive_upload(convert_to="google-slides")`` really converts an Office file.
2. ``slides_replace_text(confirm=true)`` rewrites placeholders and the change is
   visible through ``slides_get``.

Usage:

    python tests/pptx_roundtrip.py [path/to/deck.pptx]

Without an argument the script builds a minimal deck itself, which requires
``python-pptx`` in the current interpreter. If it is not installed, pass the path
to any .pptx that contains the literal placeholder ``{{NAME}}``.
"""

import asyncio
import os
import re
import sys
import tempfile
from pathlib import Path

import yaml
from googleapiclient.discovery import build
from mcp import ClientSession, StdioServerParameters
from mcp.client.stdio import stdio_client

REPO = Path(__file__).resolve().parents[1]
PLACEHOLDER = "{{NAME}}"
VALUE = "OPERATOR"

if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

from workspace_operator.auth import get_creds  # noqa: E402
from workspace_operator.config import Config  # noqa: E402

cfg = yaml.safe_load((REPO / "config.yaml").read_text(encoding="utf-8"))
checks: list[tuple[str, bool, str]] = []


def record(name: str, ok: bool, detail: str = "") -> None:
    checks.append((name, ok, detail))
    print(f"[{'PASS' if ok else 'FAIL'}] {name}" + (f" — {detail}" if detail else ""))


def text(result) -> str:
    return "\n".join(getattr(block, "text", "") or "" for block in result.content)


def build_deck(path: Path) -> bool:
    try:
        from pptx import Presentation
        from pptx.util import Inches
    except ImportError:
        return False

    prs = Presentation()
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    first = slide.shapes.add_textbox(Inches(1), Inches(1), Inches(8), Inches(2))
    first.text_frame.text = f"Hello {PLACEHOLDER}"
    second = slide.shapes.add_textbox(Inches(1), Inches(3), Inches(8), Inches(1))
    second.text_frame.text = f"Deck for {PLACEHOLDER}, generated by the smoke test"
    prs.save(path)
    return True


def trash(file_id: str) -> None:
    config = Config(
        client_secrets_file=cfg["client_secrets_file"],
        token_file=cfg["token_file"],
        backup_dir=cfg.get("backup_dir", ""),
        log_file=cfg.get("log_file"),
        mcp_auth_token=cfg.get("mcp_auth_token"),
        scopes=cfg.get("scopes") or [],
    )
    service = build("drive", "v3", credentials=get_creds(config))
    service.files().update(fileId=file_id, body={"trashed": True}).execute()


async def run(deck: Path) -> int:
    env = os.environ.copy()
    env.update(
        MCP_CONFIG_FILE=str(REPO / "config.yaml"),
        MCP_AUTH_TOKEN=str(cfg["mcp_auth_token"]),
        MCP_TOOL_PROFILE="full",
        PYTHONDONTWRITEBYTECODE="1",
    )
    params = StdioServerParameters(
        command=sys.executable, args=[str(REPO / "server.py")], env=env
    )

    presentation_id = None
    async with stdio_client(params) as (read, write):
        async with ClientSession(read, write) as session:
            await session.initialize()

            upload = await session.call_tool(
                "drive_upload",
                {"local_path": str(deck), "convert_to": "google-slides"},
            )
            upload_text = text(upload)
            match = re.search(r"ID:\s*([A-Za-z0-9_-]{10,})", upload_text)
            presentation_id = match.group(1) if match else None
            record(
                "upload pptx → Google Slides",
                not upload.is_error
                and presentation_id is not None
                and "presentation" in upload_text,
                upload_text.splitlines()[0] if upload_text else "empty",
            )

            if presentation_id:
                before = text(
                    await session.call_tool(
                        "slides_get", {"presentation_id": presentation_id}
                    )
                )
                record(
                    "placeholder survived conversion",
                    PLACEHOLDER in before,
                    f"slides={len(re.findall(r'^\d+\.', before, re.M))}",
                )

                replaced_text = text(
                    await session.call_tool(
                        "slides_replace_text",
                        {
                            "presentation_id": presentation_id,
                            "replacements": {PLACEHOLDER: VALUE},
                            "confirm": True,
                        },
                    )
                )
                occurrences = re.search(r"(\d+) occurrence", replaced_text)
                count = int(occurrences.group(1)) if occurrences else 0
                record(
                    "replace_text wrote the deck",
                    not replaced_text.startswith("Error") and count >= 2,
                    replaced_text.splitlines()[0] if replaced_text else "empty",
                )

                after = text(
                    await session.call_tool(
                        "slides_get", {"presentation_id": presentation_id}
                    )
                )
                record(
                    "placeholder gone, value present",
                    PLACEHOLDER not in after and after.count(VALUE) >= 2,
                    f"{VALUE} ×{after.count(VALUE)}",
                )

    if presentation_id:
        try:
            trash(presentation_id)
            record("cleanup", True, "presentation trashed")
        except Exception as exc:  # noqa: BLE001
            record("cleanup", False, str(exc))

    failed = [name for name, ok, _ in checks if not ok]
    print()
    print(f"{len(checks) - len(failed)}/{len(checks)} checks passed")
    return 1 if failed else 0


def main() -> int:
    if len(sys.argv) > 1:
        deck = Path(sys.argv[1]).expanduser()
        if not deck.exists():
            print(f"deck not found: {deck}")
            return 2
        return asyncio.run(run(deck))

    with tempfile.TemporaryDirectory(prefix="pptx-roundtrip-") as tmp:
        deck = Path(tmp) / "deck.pptx"
        if not build_deck(deck):
            print(
                "python-pptx is not installed in this interpreter. "
                "Pass a .pptx path that contains {{NAME}} or run with the bundled Python."
            )
            return 2
        return asyncio.run(run(deck))


if __name__ == "__main__":
    raise SystemExit(main())
